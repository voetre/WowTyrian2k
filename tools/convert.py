def emit_sheet(key, sheet, pal=None):
    items, over = sprite2_items(sheet)
    cols = 1024 // (SHEET_W + 2)
    for i, it in enumerate(items):
        it['x'] = (i % cols) * (SHEET_W + 2) + 1
