def emit_table_meta(key, sprites, atlas, tex):
    meta.append('M.tables[%s] = { count = %d, tw = %d, th = %d, tex = {%s}, gray = %s, s = {' % (
        key, len(sprites), atlas.w, atlas.h,
        ', '.join('[%d] = %s' % (k, lua_str(v.encode())) for k, v in tex.items()),
        lua_str((tex.get('gray') or '').encode()) if False else 'nil'))
    for i, s in enumerate(sprites):
        if s is None:
            continue
        vmax = 0
        for row in s['px']:
            for c in row:
                if c >= 0:
                    vmax = max(vmax, c & 0x0F)
        opaque = all(c >= 0 for row in s['px'] for c in row)
        meta.append('[%d] = {%d, %d, %d, %d, %d, %s},' % (i, s['w'], s['h'], s['x'], s['y'], vmax, 'true' if opaque else 'false'))
    meta.append('} }')


