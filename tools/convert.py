"""
WowTyrian2k asset converter.

Converts the freeware Tyrian 2.1 data files into formats the WoW client can
use:
  * Textures/*.tga  - sprite / tile / picture atlases (32-bit, top-left origin)
  * Data/*.lua      - raw game data files embedded as Lua strings, plus atlas
                      metadata
  * Sound/*.ogg     - sound effects and pre-rendered music (see build_audio)

Usage:  python3 convert.py <tyrian21 data dir> <addon dir> [--audio <dir with ogg>]

This file is part of WowTyrian2k, a port of OpenTyrian (GPL-2.0-or-later).
"""
