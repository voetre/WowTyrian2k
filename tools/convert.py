    rows = (len(items) + cols - 1) // cols
    atlas = Atlas.__new__(Atlas)
    atlas.items = items
    atlas.w = 1024
    atlas.h = pot(rows * (SHEET_H + 2))
    name = 'sheet_%s' % key
    atlas.render(name, color_with(PALETTES[SHEET_PAL if pal is None else pal]))
    atlas.render(name + '_gray', gray)
    meta.append('M.sheets[%s] = { count = %d, cols = %d, tw = %d, th = %d, tex = %s, grayTex = %s }' % (
        lua_str(key.encode()), len(items), cols, atlas.w, atlas.h,
        lua_str((TEXPATH + name).encode()), lua_str((TEXPATH + name + '_gray').encode())))
    if over:
        print('  sheet', key, 'pixels outside 12x14:', over)


