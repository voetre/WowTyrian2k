# Pictures (tyrian.pic) and tshp2.pcx
def decode_rle(data):
    img = bytearray()
    i = 0
    while i < len(data) and len(img) < 64000:
        b = data[i]
        i += 1
        if (b & 0xC0) == 0xC0:
            cnt = b & 0x3F
            v = data[i] if i < len(data) else 0
            i += 1
            img.extend([v] * cnt)
        else:
            img.append(b)
    img = img[:64000]
    img.extend(bytes(64000 - len(img)))
    return img


def write_pic(name, img, pal):
    buf = bytearray(512 * 256 * 4)
    for y in range(200):
        for x in range(320):
            r, g, b = pal[img[y * 320 + x]]
            o = (y * 512 + x) * 4
            buf[o:o + 4] = bytes((b, g, r, 255))
    write_tga(name, 512, 256, buf)


